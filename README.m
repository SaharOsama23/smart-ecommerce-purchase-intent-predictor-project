# smart-ecommerce-purchase-intent-predictor-project
A Machine Learning project that predicts online shoppers' purchase intention using the UCI Online Shoppers Purchasing Intention dataset. Includes data preprocessing, exploratory data analysis (EDA), feature engineering, model training, and performance evaluation to identify customers likely to complete a purchase.
## Project Overview
An end-to-end Machine Learning project that aims to predict online shoppers' purchase intention using the UCI Online Shoppers Purchasing Intention dataset.
